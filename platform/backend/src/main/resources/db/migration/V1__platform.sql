CREATE TABLE account (
 id uuid PRIMARY KEY, email varchar(254) UNIQUE NOT NULL, password_hash varchar(100) NOT NULL,
 role varchar(20) NOT NULL, enabled boolean NOT NULL
);
CREATE TABLE playlist (
 id uuid PRIMARY KEY, owner_id uuid NOT NULL REFERENCES account(id) ON DELETE CASCADE,
 label varchar(250) NOT NULL, dns varchar(20) NOT NULL, created_at timestamptz NOT NULL
);
CREATE INDEX playlist_owner ON playlist(owner_id, created_at DESC);
CREATE TABLE channel (
 id uuid PRIMARY KEY, playlist_id uuid NOT NULL REFERENCES playlist(id) ON DELETE CASCADE,
 name varchar(512) NOT NULL, category varchar(512) NOT NULL, kind varchar(20) NOT NULL,
 source text NOT NULL, position bigint NOT NULL, tvg_id varchar(512)
);
CREATE INDEX channel_playlist ON channel(playlist_id, position);
CREATE INDEX channel_category ON channel(playlist_id, kind, category);
CREATE TABLE favorite (
 account_id uuid NOT NULL REFERENCES account(id) ON DELETE CASCADE,
 channel_id uuid NOT NULL REFERENCES channel(id) ON DELETE CASCADE,
 PRIMARY KEY(account_id, channel_id)
);
CREATE TABLE audit_event (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor varchar(254) NOT NULL,
 action varchar(100) NOT NULL, happened_at timestamptz NOT NULL
);
CREATE TABLE platform_setting (name varchar(60) PRIMARY KEY, value varchar(1000) NOT NULL);
CREATE TABLE epg_source (id uuid PRIMARY KEY, label varchar(250) NOT NULL, source text NOT NULL, updated_at timestamptz);
CREATE TABLE epg_program (
 source_id uuid NOT NULL REFERENCES epg_source(id) ON DELETE CASCADE,
 channel_code varchar(512) NOT NULL, starts_at timestamptz NOT NULL, ends_at timestamptz NOT NULL,
 title varchar(512) NOT NULL, PRIMARY KEY(source_id, channel_code, starts_at)
);
CREATE INDEX epg_program_channel ON epg_program(channel_code, starts_at);
